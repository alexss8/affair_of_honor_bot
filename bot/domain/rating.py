"""Турнирный рейтинг по Elo: победа над сильным даёт много очков, над слабым — мало.

Поэтому частые бои со слабыми соперниками не поднимают игрока в таблице турнира.
"""

START_RATING = 1500
K_FACTOR = 32  # максимум очков за один бой


def elo_delta(winner_rating: int, loser_rating: int) -> int:
    """Сколько очков победитель забирает у проигравшего (не меньше 1).

    Ожидаемый результат победителя E = 1 / (1 + 10^((R_loser − R_winner) / 400)); очки = K · (1 − E).
    """
    expected = 1 / (1 + 10 ** ((loser_rating - winner_rating) / 400))
    return max(1, round(K_FACTOR * (1 - expected)))
